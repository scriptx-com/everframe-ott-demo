import type { Episode, Title } from './catalog';

// The second half of the catalogue: enough titles that every rail scrolls.
// Like the rest, all names, people and artwork are original to this demo.

function eps(list: Array<[string, number, string]>): Episode[] {
  return list.map(([title, length, blurb], i) => ({ id: `e${i + 1}`, number: i + 1, title, length, blurb, progress: 0 }));
}

